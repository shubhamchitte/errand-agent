"""Collect one row per scenario and write EVAL_TABLE.md at the end of the run (generated, never hand-written)."""
from __future__ import annotations

from pathlib import Path

import pytest

from evals.harness import Eval

ROOT = Path(__file__).resolve().parent.parent
_ROWS: list[dict] = []


def pytest_configure(config):
    config.addinivalue_line("markers", "scenario(category, expected): eval scenario metadata")


@pytest.fixture
def ev():
    return Eval()


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    out = yield
    rep = out.get_result()
    m = item.get_closest_marker("scenario")
    if m is None or rep.when not in ("setup", "call"):
        return
    if rep.when == "setup" and rep.passed:
        return
    e = item.funcargs.get("ev")
    if e is not None:
        _ROWS[:] = [r for r in _ROWS if r["id"] != item.nodeid]
        note = e.notes_text
        if not rep.passed:
            tail = str(call.excinfo.value).strip().splitlines()[:1] if call.excinfo else []
            note = (note + " | " if note else "") + "FAILED: " + (tail[0][:140] if tail else "error")
        _ROWS.append({"id": item.nodeid, "name": item.name.removeprefix("test_"), "category": m.kwargs.get("category", ""),
                      "expected": m.kwargs.get("expected", ""), "actual": e.actual_text or "(not reached)",
                      "ok": rep.passed, "notes": note})


def _cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def pytest_sessionfinish(session, exitstatus):
    if not _ROWS:
        return
    passed = sum(r["ok"] for r in _ROWS)
    cats = sorted({r["category"] for r in _ROWS})
    lines = ["# Eval table", "",
             "Generated by `python -m pytest evals` (evals/conftest.py). Do not edit by hand.", "",
             f"{passed}/{len(_ROWS)} scenarios pass across {len(cats)} categories. Every scenario drives the real agent "
             "loop with a scripted model, forced mock outcomes and a fake clock; assertions are on outcomes and "
             "invariants, never reply wording.", "",
             "| scenario | category | expected | actual | pass/fail | notes |", "|---|---|---|---|---|---|"]
    for r in _ROWS:
        lines.append(f"| {r['name']} | {_cell(r['category'])} | {_cell(r['expected'])} | {_cell(r['actual'])} | "
                     f"{'PASS' if r['ok'] else 'FAIL'} | {_cell(r['notes'])} |")
    (ROOT / "EVAL_TABLE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
